export function getAssetDefinition(id: string): AssetDefinition {
  const found = ASSET_CATALOG.find((a) => a.id === id);
  if (found) return found;
  return {
    id,
    name: id.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()),
    category: 'decorations',
    description: 'Festive decorative object',
    previewIcon: '✨',
    defaultScale: [1, 1, 1],
  };
}

export function isAssetUnlocked(assetId: string, unlockedList?: string[]): boolean {
  if (DEFAULT_FREE_ASSET_IDS.includes(assetId)) return true;
  if (!unlockedList) return false;
  return unlockedList.includes(assetId);
}
